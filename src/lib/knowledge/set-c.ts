import type { Article } from "./types";
import { biliSearch, makeArticle, type DoseIn } from "./helpers";

function art(
  slug: string,
  title: string,
  subtitle: string,
  summary: string,
  problems: string[],
  crops: string[],
  regions: string[],
  seasons: string[],
  look: string,
  when: string,
  cropsPlain: string,
  c1: [string, string, string],
  c2: [string, string, string],
  plain: string,
  nat: string[],
  hum: string[],
  steps: string[],
  dosages: DoseIn[],
  keyword: string,
  related: string[],
  extra?: Partial<Article>,
): Article {
  return makeArticle({
    slug,
    title,
    subtitle,
    summary,
    crops,
    problems,
    regions,
    seasons,
    tags: [...problems, slug],
    coverCrop: extra?.coverCrop ?? null,
    coverType: extra?.coverType ?? "soil",
    photos: extra?.photos,
    phenomenon: { appearance: look, conditions: when, commonCrops: cropsPlain },
    confuseWith: [
      { other: c1[0], difference: c1[1], lookAt: c1[2] },
      { other: c2[0], difference: c2[1], lookAt: c2[2] },
    ],
    causes: { natural: nat, human: hum, plainExplain: plain },
    solutions: { steps, videos: extra?.solutions?.videos ?? [biliSearch(keyword)] },
    dosages,
    prevention: extra?.prevention ?? ["按测土和当地农技站，宁少勿多。", "先看根和土面，再决定补什么。", "有机肥和耕作一起改。"],
    indicators: extra?.indicators ?? [
      { name: "pH / 有机质 / 盐分", meaning: "先读这三项", typical: "再看氮磷钾和微量元素" },
      { name: "田间对照", meaning: "叶位、根、土面", typical: "和邻地健康株比" },
    ],
    relatedSlugs: related,
    featured: extra?.featured,
    hot: extra?.hot,
  });
}

