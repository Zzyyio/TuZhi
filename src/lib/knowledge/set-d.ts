import type { Article } from "./types";
import { biliSearch, makeArticle, type DoseIn } from "./helpers";

function art(
  slug: string,
  title: string,
  subtitle: string,
  summary: string,
  problems: string[],
  crops: string[],
  regions: string[],
  seasons: string[],
  look: string,
  when: string,
  cropsPlain: string,
  c1: [string, string, string],
  c2: [string, string, string],
  plain: string,
  nat: string[],
  hum: string[],
  steps: string[],
  dosages: DoseIn[],
  keyword: string,
  related: string[],
  extra?: Partial<Article>,
): Article {
  return makeArticle({
    slug,
    title,
    subtitle,
    summary,
    crops,
    problems,
    regions,
    seasons,
    tags: [...problems, slug],
    coverCrop: extra?.coverCrop ?? null,
    coverType: extra?.coverType ?? "soil",
    photos: extra?.photos,
    phenomenon: { appearance: look, conditions: when, commonCrops: cropsPlain },
    confuseWith: [
      { other: c1[0], difference: c1[1], lookAt: c1[2] },
      { other: c2[0], difference: c2[1], lookAt: c2[2] },
    ],
    causes: { natural: nat, human: hum, plainExplain: plain },
    solutions: { steps, videos: [biliSearch(keyword)] },
    dosages,
    prevention: extra?.prevention ?? ["按测土和农技站，宁少勿多。", "先看根、叶位和土面。", "用药和施肥都不要加倍。"],
    indicators: extra?.indicators ?? [{ name: "田间时间线", meaning: "喷药或施肥后多久出现", typical: "1～3 天突发更像药害/肥害" }],
    relatedSlugs: related,
    featured: extra?.featured,
    hot: extra?.hot,
  });
}

