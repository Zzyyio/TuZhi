def main() -> None:
    used_hash.clear()
    report = {"copied": [], "kept": [], "filled": [], "fail": []}

    # 1) copy curated searched photos (overwrite dest)
    for sid, rel in SEARCHED_MAP.items():
        src = SEARCHED / f"{sid}.jpg"
        dest = IMG / rel if rel.endswith(".jpg") and not rel.startswith("articles/") else ART / Path(rel).name
        if "/" in rel:
            dest = Path("/workspace/public/images") / rel
        if copy_file(src, dest):
            print("COPY", sid, "->", dest.name)
            report["copied"].append(dest.name)
        else:
            print("SKIP copy", sid)

    # 2) keep verified existing article covers in the hash set
    for slug in KEEP_ART:
        p = ART / f"{slug}.jpg"
        if p.exists():
            used_hash.add(hashlib.md5(p.read_bytes()).hexdigest())
            report["kept"].append(slug)

    # 3) build a downloadable pool from Wikimedia categories + named files
    pool: list[dict] = []
    seen_u = set()
    print("fetch categories")
    for cat in CATEGORIES:
        for it in category_files(cat, 35):
            if it["url"] in seen_u:
                continue
            seen_u.add(it["url"])
            pool.append(it)
        print("  cat", cat, "pool", len(pool))

    print("fetch named files")
    for name in WIKI_POOL:
        url = wiki_file_url(name)
        if not url or url in seen_u:
            continue
        seen_u.add(url)
        pool.append({"url": url, "title": name})
    print("pool size", len(pool))

    def take_for(keys: list[str], dest: Path, extra_q: str | None = None) -> bool:
        ranked = sorted(pool, key=lambda it: score(it["title"], keys), reverse=True)
        for it in ranked:
            if it["url"] in used_url:
                continue
            if keys and score(it["title"], keys) < 1:
                continue
            raw = get(it["url"], timeout=30)
            if not raw:
                continue
            if save_unique(raw, dest):
                used_url.add(it["url"])
                print("OK", dest.name, it["title"][:70])
                return True
        # Openverse fallback
        queries = extra_q and [extra_q] or [" ".join(keys[:2]) + " farmland"]
        for q in queries:
            for it in openverse(q):
                if it["url"] in used_url:
                    continue
                raw = get(it["url"], timeout=30)
                if not raw:
                    continue
                if save_unique(raw, dest):
                    used_url.add(it["url"])
                    print("OV", dest.name, it["title"][:70])
                    return True
        return False

    # 4) fill missing / junk primary covers
    for slug in SLUGS:
        dest = ART / f"{slug}.jpg"
        already = dest.exists() and hashlib.md5(dest.read_bytes()).hexdigest() in used_hash
        # overwrite if this slug was not copied/kept
        copied_name = f"{slug}.jpg"
        if copied_name in report["copied"] or slug in KEEP_ART:
            # still need unique -2 maybe
            pass
        else:
            keys = KEYS.get(slug) or [slug.replace("-", " ")]
            if take_for(keys, dest, extra_q=" ".join(keys[:2]) + " field"):
                report["filled"].append(slug)
            else:
                report["fail"].append(slug)
                print("FAIL", slug)

        dest2 = ART / f"{slug}-2.jpg"
        if dest2.exists() and hashlib.md5(dest2.read_bytes()).hexdigest() in used_hash and copied_name.replace(".jpg", "-2.jpg") in report["copied"]:
            continue
        # fill -2 if missing or duplicate of primary
        need2 = True
        if dest2.exists() and dest.exists():
            if hashlib.md5(dest2.read_bytes()).hexdigest() != hashlib.md5(dest.read_bytes()).hexdigest():
                if hashlib.md5(dest2.read_bytes()).hexdigest() in used_hash:
                    # may be unique already; still ok to replace junk later
                    need2 = dest2.stat().st_size < 20_000
        if need2:
            keys = KEYS.get(slug) or [slug.replace("-", " ")]
            take_for(keys + ["closeup", "soil"], dest2, extra_q=" ".join(keys[:2]) + " closeup")

    # 5) wiki term covers
    for wid in WIKI_IDS:
        dest = WIKI / f"{wid}.jpg"
        keys = WIKI_KEYS.get(wid) or [wid]
        if not dest.exists() or hashlib.md5(dest.read_bytes()).hexdigest() not in used_hash or True:
            # always assign unique wiki cover
            if take_for(keys, dest, extra_q=" ".join(keys[:2]) + " soil"):
                report["filled"].append("wiki:" + wid)
            else:
                report["fail"].append("wiki:" + wid)
        dest2 = WIKI / f"{wid}-2.jpg"
        take_for(keys + ["field"], dest2, extra_q=" ".join(keys[:2]) + " farmland")

    # 6) extras
    extras = {
        "hero-field": (IMG / "hero-field.jpg", ["plough", "tilled", "farmland"]),
        "healthy-soil": (IMG / "healthy-soil.jpg", ["loam", "crumb", "dark soil"]),
        "soil-profile": (IMG / "soil-profile.jpg", ["profile", "horizon", "soil pit"]),
    }
    if not (IMG / "olivine.jpg").exists():
        extras["olivine"] = (IMG / "olivine.jpg", ["olivine", "forsterite", "peridot"])
    for name, (dest, keys) in extras.items():
        if dest.exists() and name != "hero-field":
            # still refresh hero if we have a pool hit
            pass
        take_for(keys, dest, extra_q=" ".join(keys) + " photograph")

    # uniqueness report
    hashes: dict[str, list[str]] = {}
    missing = []
    for slug in SLUGS:
        p = ART / f"{slug}.jpg"
        if not p.exists():
            missing.append(slug)
            continue
        h = hashlib.md5(p.read_bytes()).hexdigest()
        hashes.setdefault(h, []).append(slug)
    dups = {k: v for k, v in hashes.items() if len(v) > 1}
    print("UNIQUE", len(hashes), "of", len(SLUGS) - len(missing), "missing", missing, "dups", dups)
    wiki_h = {}
    for wid in WIKI_IDS:
        p = WIKI / f"{wid}.jpg"
        if not p.exists():
            print("WIKI MISSING", wid)
            continue
        wiki_h.setdefault(hashlib.md5(p.read_bytes()).hexdigest(), []).append(wid)
    print("WIKI UNIQUE", len(wiki_h), "of", len(WIKI_IDS), "dups", {k: v for k, v in wiki_h.items() if len(v) > 1})
    print("olivine", (IMG / "olivine.jpg").exists())
    (Path("/tmp/photo-report.json")).write_text(json.dumps({"copied": report["copied"], "kept": report["kept"], "filled": report["filled"], "fail": report["fail"], "dups": dups}, ensure_ascii=False, indent=2))


