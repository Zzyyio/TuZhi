def get(url: str, timeout: int = 25) -> bytes | None:
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "*/*"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=timeout) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            if e.code == 429:
                time.sleep(8 + attempt * 6)
                continue
            return None
        except Exception:
            time.sleep(1.2)
    return None


def bad_meta(title: str, url: str) -> bool:
    t = (title or "").lower()
    u = (url or "").lower()
    if any(s in t for s in SKIP_TITLE):
        return True
    if any(s in u for s in SKIP_URL):
        return True
    if t.endswith(".djvu") or t.endswith(".pdf") or "file:" in t and ".djvu" in t:
        return True
    return False


def save_unique(src: bytes, dest: Path) -> bool:
    try:
        im = Image.open(BytesIO(src))
        im = im.convert("RGB")
    except Exception:
        return False
    w, h = im.size
    if min(w, h) < 220 or w * h < 80_000:
        return False
    im.thumbnail((1400, 1400))
    buf = BytesIO()
    im.save(buf, "JPEG", quality=84, optimize=True)
    data = buf.getvalue()
    hsh = hashlib.md5(data).hexdigest()
    if hsh in used_hash:
        return False
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)
    used_hash.add(hsh)
    return True


def copy_file(src: Path, dest: Path) -> bool:
    if not src.exists():
        return False
    return save_unique(src.read_bytes(), dest)


def wiki_file_url(name: str) -> str | None:
    qs = urllib.parse.urlencode(
        {
            "action": "query",
            "titles": f"File:{name}",
            "prop": "imageinfo",
            "iiprop": "url|size|mime",
            "iiurlwidth": 1400,
            "format": "json",
        }
    )
    raw = get(f"https://commons.wikimedia.org/w/api.php?{qs}")
    time.sleep(0.25)
    if not raw:
        return None
    try:
        data = json.loads(raw.decode("utf-8", "replace"))
    except Exception:
        return None
    pages = (data.get("query") or {}).get("pages") or {}
    for p in pages.values():
        info = (p.get("imageinfo") or [{}])[0]
        mime = (info.get("mime") or "").lower()
        if "image/" not in mime:
            continue
        url = info.get("thumburl") or info.get("url")
        title = p.get("title") or name
        if url and not bad_meta(title, url):
            return url
    return None


def category_files(cat: str, limit: int = 40) -> list[dict]:
    qs = urllib.parse.urlencode(
        {
            "action": "query",
            "generator": "categorymembers",
            "gcmtitle": cat,
            "gcmtype": "file",
            "gcmlimit": limit,
            "prop": "imageinfo",
            "iiprop": "url|size|mime",
            "iiurlwidth": 1400,
            "format": "json",
        }
    )
    raw = get(f"https://commons.wikimedia.org/w/api.php?{qs}")
    time.sleep(0.35)
    if not raw:
        return []
    try:
        data = json.loads(raw.decode("utf-8", "replace"))
    except Exception:
        return []
    out = []
    pages = (data.get("query") or {}).get("pages") or {}
    for p in pages.values():
        info = (p.get("imageinfo") or [{}])[0]
        mime = (info.get("mime") or "").lower()
        url = info.get("thumburl") or info.get("url") or ""
        title = p.get("title") or ""
        if not url or "image/" not in mime:
            continue
        if bad_meta(title, url):
            continue
        out.append({"url": url, "title": title})
    return out


def openverse(q: str) -> list[dict]:
    qs = urllib.parse.urlencode(
        {"q": q, "page_size": 16, "page": 1, "mature": "false", "license_type": "all"}
    )
    raw = get(f"https://api.openverse.org/v1/images/?{qs}")
    time.sleep(0.3)
    if not raw:
        return []
    try:
        data = json.loads(raw.decode("utf-8", "replace"))
    except Exception:
        return []
    out = []
    for it in data.get("results") or []:
        url = it.get("url") or ""
        title = it.get("title") or ""
        if not url or bad_meta(title, url):
            continue
        # require at least one farm-ish word
        blob = (title + " " + url).lower()
        if not any(
            w in blob
            for w in (
                "soil", "farm", "field", "maize", "corn", "wheat", "tomato", "rice",
                "paddy", "leaf", "root", "crop", "plant", "seedling", "orchard",
                "tea", "potato", "manure", "compost", "salt", "lime", "plough",
                "plow", "tractor", "greenhouse", "irrigation", "straw",
            )
        ):
            continue
        out.append({"url": url, "title": title})
    return out


def score(title: str, keys: list[str]) -> int:
    t = title.lower()
    return sum(1 for k in keys if k.lower() in t)


