from pathlib import Path

def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def slist(xs):
    return "[" + ", ".join(q(x) for x in xs) + "]"

def emit(p: dict) -> str:
    confuse = ",\n        ".join(
        "{ lookalike: %s, difference: %s, photoHint: %s }" % (q(a), q(b), q(c))
        for a, b, c in p["confuse"]
    )
    doses = ",\n        ".join(
        "{ name: %s, range: %s, note: %s }" % (q(a), q(b), q(c))
        for a, b, c in p["dosage"]
    )
    inds = ",\n        ".join(
        "{ name: %s, meaning: %s, typical: %s }" % (q(a), q(b), q(c))
        for a, b, c in p["ind"]
    )
    return f'''  {q(p["slug"])}: {{
    uniqueAngle: {q(p["angle"])},
    subtitle: {q(p["sub"])},
    summary: {q(p["summary"])},
    fieldCheck: {q(p["field"])},
    dontDo: {slist(p["dont"])},
    whenToTest: {q(p["when"])},
    prevention: {slist(p["prev"])},
    phenomenon: {{ appearance: {q(p["appear"])}, conditions: {q(p["cond"])}, commonCrops: {q(p["crops"])} }},
    confuse: [
        {confuse}
    ],
    causes: {{
      plainExplain: {q(p["plain"])},
      natural: {slist(p["nat"])},
      human: {slist(p["hum"])},
    }},
    dosage: [
        {doses}
    ],
    relatedSlugs: {slist(p["rel"])},
    steps: {slist(p["steps"])},
    indicators: [
        {inds}
    ],
  }}'''

